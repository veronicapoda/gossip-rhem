  idcode <- as.character(GossipData$info[[gender_data_name]]$idcode)
  
  for (Wave in waves) {
    cat("Processing", Wave, "\n")
    
    # Construct the file path for the friendship matrix
    friend_scale <- switch(Wave,
                           Wave1 = "15",
                           Wave2 = "11",
                           Wave3 = "19",
                           Wave4 = "20")
    friend_scale_all <- switch(Wave,
                               Wave1 = "15_1",
                               Wave2 = "11_2h",
                               Wave3 = "19_3h",
                               Wave4 = "20_4h")
    # Path
    base_folder <- getwd() 
    csv_file <- file.path(
      base_folder,
      "gossipdata_analysis",
      "gossipdata",
