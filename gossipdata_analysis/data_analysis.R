        dplyr::mutate(SenderSet = sapply(Senders, function(x) paste(sort(x), collapse = ","))) %>%
        dplyr::distinct(SenderSet, Receiver, Time, .keep_all = TRUE) %>%
        dplyr::select(-SenderSet)
      
      # Append to the global risk set list
      risk_set_list <- append(risk_set_list, list(risk_df))
    }
  }
}
