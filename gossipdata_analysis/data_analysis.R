################################################################################
# Compute endogenous covariate based on average evaluation 
################################################################################

# Initialize history and covariates
history_data <- list(time = numeric(0), receiver = character(0), sender = list())
cov_past    <- vector("list", length(endogenous_covariates))
cov_current <- vector("list", length(endogenous_covariates))
cov_avg     <- vector("list", length(endogenous_covariates))
names(cov_past)    <- endogenous_covariates
names(cov_current) <- endogenous_covariates
names(cov_avg)     <- endogenous_covariates


# Loop over events
for (i in 1:nrow(Risk_set_df)) {
  # Current event
  sender_i <- Risk_set_df$Senders[[i]]
  if (is.null(sender_i)) sender_i <- character(0)
  e <- list(
    time     = Risk_set_df$Time[i],
    receiver = Risk_set_df$Receiver[i],
    sender   = sender_i
  )
  
  # Past: history up to previous wave
  past_idx <- which(history_data$time < e$time)
  if(length(past_idx) == 0){
    history_past <- list(time = numeric(0), receiver = character(0), sender = list())
  } else {
    history_past <- list(
      time     = history_data$time[past_idx],
      receiver = history_data$receiver[past_idx],
      sender   = history_data$sender[past_idx]
    )
  }
  
  # Current: history up to current wave (included)
  if(length(history_data$time) == 0){
    history_current <- list(time = numeric(0), receiver = character(0), sender = list())
  } else {
    history_current <- history_data
  }
  e_current <- e
  e_current$time <- e_current$time + 1  # Include current wave
  
  # Compute covariate for Past, Current & Average
  for (cov in endogenous_covariates) {
    
    # Past
    if(length(history_past$time) == 0){
      cov_past[[cov]][i] <- 0
    } else {
      cov_past[[cov]][i] <- compute_covariates(CovariateName = cov, History = history_past, Event = e)
    }
    
    # Current
    if(length(history_current$time) == 0){
      cov_current[[cov]][i] <- 0
    } else {
      cov_current[[cov]][i] <- compute_covariates(CovariateName = cov, History = history_current, Event = e_current)
    }
    
    # Average
    cov_avg[[cov]][i] <- (cov_past[[cov]][i] + cov_current[[cov]][i]) / 2
  }
  
  # Update history only if z=1
  if (z_data[i] == 1) {
    history_data$time     <- c(history_data$time, e$time)
    history_data$receiver <- c(history_data$receiver, e$receiver)
    history_data$sender   <- append(history_data$sender, list(e$sender))
  }
}

