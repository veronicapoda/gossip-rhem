################################################################################
# Fit a Generalized Additive Model (GAM) using bam() from mgcv
################################################################################

library(mgcv)

# Formula
formula <- z ~ girl.alter + 
  s(girl.ego) + 
  s(time_continuous, k=4) +    
  s(log(sender_degree +1)) +
  s(log(receiver_degree +1), k=8) + 
  s(repetition, k=4) +
  s(subset_repetition) +
  s(reciprocity) + 
  s(transitive_closure, k=6) + 
  s(cyclic_closure) + 
  s(sender_balance) + 
  s(receiver_balance, k=8) + 
  s(ClassGroup, bs="re") +
  s(ReceiverGroup, bs="re") +
  s(SenderGroup, bs="re") +
  offset(offset_log)             # offset term



model_with_re <- bam(
  formula,
  data = data_df,
  family = binomial(link = "cloglog"),
  method = "fREML",
  select = TRUE,      # penalize irrelevant smooth terms
  discrete = TRUE     # faster for large datasets
)

# Summary
