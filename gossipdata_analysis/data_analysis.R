# Helper function: check if a student ID is valid according to its gender group
is_valid_id <- function(id) {
  if (is.na(id) || id == "") return(FALSE)
  id_chr <- as.character(id)
  gender_key <- paste0("gender_", substr(id_chr, 1, 2), "00")
  if (!gender_key %in% names(GossipData$info)) return(FALSE)
  return(as.numeric(id) %in% as.numeric(GossipData$info[[gender_key]]$idcode))
}




