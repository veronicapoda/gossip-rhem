      friend_scale, # e.g., "friend_scale1"
      paste0(class, "_", friend_scale_all, ".csv")
    )
    # Skip wave if file is missing
    if (!file.exists(csv_file)) {
      cat("CSV not found, skipping", Wave, "\n")
      next
    }
    friend <- read.csv(csv_file, row.names = 1)
    matrix_data <- as.matrix(friend)
    students <- rownames(matrix_data)
    
    # Skip if no valid student IDs are found for this class
    if (!any(substr(students, 1, 1) == substr(as.character(class), 1, 1))) {
      cat("No valid students found for this class, skipping", Wave, "\n")
      next
    }
    
    # Load gossip (negative gossip) data for the same class and wave
    if (Wave == "Wave1") {
      neg_gossip <- "33"
      neg_gossip_all <- "33_3"
    } else if (Wave == "Wave2") {
      neg_gossip <- "32"
      neg_gossip_all <- "32_3_2h"
    } else if (Wave == "Wave3") {
      neg_gossip <- "39"
      neg_gossip_all <- "39_3_3h"
    } else if (Wave == "Wave4") {
      neg_gossip <- "38"
      neg_gossip_all <- "38_3_4h"
    }
    # Path 
    base_folder <- getwd()  
    ngossip_path <- file.path(
      base_folder,
      "gossipdata_analysis",
      "gossipdata",
      "RECENS_Wired_into_each_other-Data_files",
      "RECENS_networks_dataset_w1234",
      Wave,
      folder,
      class,
      neg_gossip,
      paste0(class, "_", neg_gossip_all, ".csv")
    )
    NGossip <- read.csv(ngossip_path, row.names = 1)
    gossip_data <- as.matrix(NGossip)
    rows <- rownames(gossip_data)
    cols <- colnames(gossip_data)
    
    # All students mentioned in the gossip dataset
    all_students_class <- unique(c(rows, sub("^X", "", cols)))
    
    # Keep only valid individual IDs using the helper function
    valid_students <- all_students_class[sapply(all_students_class, is_valid_id)]
    
    # Extract reciprocated friendships
    indices <- which(matrix_data == 2, arr.ind = TRUE)
    pairs_of_friends <- t(apply(indices, 1, function(idx) {
      c(students[idx[1]], sub("^X", "", students[idx[2]]))
    }))
    pairs_sorted <- t(apply(pairs_of_friends, 1, sort))
    pairs_sorted <- pairs_sorted[pairs_sorted[,1] != pairs_sorted[,2], ]
    reciprocated_friends <- pairs_sorted[duplicated(pairs_sorted), ]
    
    # Skip this wave if no reciprocated friendships exist
    if (is.null(reciprocated_friends) || length(reciprocated_friends) == 0) {
      cat("No reciprocated friendships found, skipping this wave\n")
      next 
    }
    
    # Ensure data is always in matrix form
    if (is.vector(reciprocated_friends) && length(reciprocated_friends) == 2) {
      reciprocated_friends <- matrix(reciprocated_friends, ncol = 2, byrow = TRUE)
    } else if (!is.matrix(reciprocated_friends)) {
      reciprocated_friends <- as.matrix(reciprocated_friends)
    }
    
    # Filter friendship pairs to include only valid students
    filtered_friendships <- lapply(1:nrow(reciprocated_friends), function(i) as.character(reciprocated_friends[i,]))
    filtered_friendships <- Filter(function(pair) all(pair %in% students), filtered_friendships)
    if (length(filtered_friendships) == 0) next
    filtered_friendships_matrix <- do.call(rbind, filtered_friendships)
    
    # Generate the risk set for the current class and wave
    risk_df <- generate_risk_set(max_senders = max_senders, Wave = as.numeric(gsub("Wave","",Wave)))
    
